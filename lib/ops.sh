#@lib Optimalisatie, healthcheck, logrotate en geplande herstart — wordt door ark-manager.sh ge-sourced; enkel functies, geen top-level acties.
#═══════════════════════════════════════════════════════════════════════════════
#  OPTIMIZATION / HEALTHCHECK / LOGROTATE
